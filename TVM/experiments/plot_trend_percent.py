import matplotlib
import matplotlib.pyplot as plt
import numpy as np


def plot_coverage(data, granularity):
    time_points = np.linspace(0, 12, num=25)
    ticks = range(0, 13, 1)

    plt.figure(figsize=(10, 7))
    styles = {
        "HARLO": ("-o", "#2ca02c"),
        "NNSmith": ("--s", "#ff7f0e"),
        "WhiteFox": (":x", "#9467bd"),
        "OATest": ("-.v", "#1f99b4"),
    }

    for method, coverage in data.items():
        line_style, color = styles.get(method, ("-", "black"))
        plt.plot(time_points, coverage, line_style, color=color, label=method, markersize=9, linewidth=3)

    font_size = 38
    plt.xlabel("Time (hours)", fontweight="bold")
    plt.ylabel(f"{granularity} Coverage (%)", fontweight="bold")
    plt.xticks(ticks, fontsize=font_size, fontweight="bold")
    plt.yticks( fontweight="bold")

    plt.tight_layout()
    plt.legend(loc='lower right',
               prop={'size': 24, 'weight': 'bold'},
               handletextpad=0.5,
               labelspacing=0.15,
               borderpad=0.3,
               framealpha=0.5,
               bbox_to_anchor=(1.01, -0.02),
               )
    plt.savefig(f"trends_tvm_{granularity}.pdf")
    plt.show()


