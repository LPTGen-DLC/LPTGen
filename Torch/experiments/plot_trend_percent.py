def plot_coverage(data, granularity):
    # time_points = list(range(1, 21))
    time_points = np.linspace(0, 12, num=25)
    ticks = range(0, 13, 1)
    # print(time_points)
    # print(list(ticks))

    plt.figure(figsize=(10, 7))
    styles = {
        'LPTGen':  ('-o', '#2ca02c'),  # 绿色
        'NNSmith': ('--s', '#ff7f0e'),  # 橙色
        'WhiteFox': (':x', '#9467bd'),    # 红色
        'OATest': ('-.v', '#1f99b4'),  # 蓝色
    }

    for method, coverage in data.items():
        line_style, color = styles.get(method, ('-', 'black'))
        plt.plot(time_points, coverage, line_style, color=color, label=method,
                 markersize=9, linewidth=3)

    font_size = 38
    # plt.title('Coverage Over Time')
    plt.xlabel('Time (hours)', fontsize=font_size, fontweight='bold')
    plt.ylabel(f'{granularity} Coverage (%)', fontsize=font_size, fontweight='bold')
    plt.xticks(ticks, fontsize=font_size, fontweight='bold')
    if granularity == 'Branch':
        plt.yticks(np.arange(0, 16, 5), fontsize=font_size, fontweight='bold')
    else:
        plt.yticks(fontsize=font_size, fontweight='bold')

    plt.tight_layout()
    plt.legend(loc='lower right',
               prop={'size': 24, 'weight': 'bold'},
               handletextpad=0.5,      # 标记和文字间距
               labelspacing=0.15,
               borderpad=0.3,
               framealpha=0.5,
               bbox_to_anchor=(1.01, -0.02),  # 下移一些
               )
    plt.savefig(f"trends_{granularity}.pdf")
    plt.show()


